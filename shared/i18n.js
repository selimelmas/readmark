  async init(savedLang) {
    if (savedLang && savedLang !== 'system' && this.locales[savedLang]) {
      this.currentLang = savedLang;
    } else {
      let detected = 'en';
      try {
        const raw = (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage ? chrome.i18n.getUILanguage() : (typeof navigator !== 'undefined' ? (navigator.language || 'en') : 'en')).replace('-', '_');
        if (this.locales[raw]) detected = raw;
        else {
          const short = raw.split('_')[0].toLowerCase();
          if (this.locales[short]) detected = short;
        }
      } catch {}
      this.currentLang = this.locales[detected] ? detected : 'en';
    }
    return this.currentLang;
  },

  t(key, fallback = '') {
    const locale = this.locales[this.currentLang] || this.locales.en || this.locales.tr;
    return locale?.[key] || this.locales.en?.[key] || this.locales.tr?.[key] || fallback || key;
  },

  async setLang(lang) {
    if (lang === 'system') {
      await this.init('system');
      this.applyTranslations();
      return true;
    }
    if (this.locales[lang]) {
      this.currentLang = lang;
      this.applyTranslations();
      return true;
    }
    return false;
  },

  applyTranslations(root = document) {
    root.querySelectorAll('[data-i18n],[data-i18n-placeholder],[data-i18n-title],[data-i18n-aria]').forEach(el => {
      if (el.dataset.i18n) el.textContent = this.t(el.dataset.i18n);
      if (el.dataset.i18nPlaceholder) el.placeholder = this.t(el.dataset.i18nPlaceholder);
      if (el.dataset.i18nTitle) el.title = this.t(el.dataset.i18nTitle);
      if (el.dataset.i18nAria) el.setAttribute('aria-label', this.t(el.dataset.i18nAria));
    });
  }
